'use strict';
/* v0.2.148: user-selected Default/Satellite/Topographic survives app reloads. */
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const app=fs.readFileSync('openrf/static/app.js','utf8');
const html=fs.readFileSync('openrf/static/index.html','utf8');
const start=app.indexOf('const MAP_BASEMAP_PREFERENCE_KEY =');
const end=app.indexOf('function rememberedPage()',start);
assert(start>0&&end>start);
const script=app.slice(start,end);
const store=new Map();
const context={window:{localStorage:{getItem:key=>store.get(key)??null,setItem:(key,val)=>store.set(key,val)}}};
vm.runInNewContext(script,context);
const key='openrf.map.basemap.v1';
assert.equal(context.rememberedBaseMap(),'default');
context.rememberBaseMap('satellite');
assert.equal(store.get(key),'satellite');
assert.equal(context.rememberedBaseMap(),'satellite','Selection survives a new page boot');
context.rememberBaseMap('topographic');
assert.equal(context.rememberedBaseMap(),'topographic');
context.rememberBaseMap('default');
assert.equal(context.rememberedBaseMap(),'default');
store.set(key,'other-unapproved-source');
assert.equal(context.rememberedBaseMap(),'default','Only approved basemap identifiers restore');
store.set(key,'null');
assert.equal(context.rememberedBaseMap(),'default');
const denied={window:{localStorage:{getItem(){throw Error('blocked');},setItem(){throw Error('blocked');}}}};
vm.runInNewContext(script,denied);
assert.equal(denied.rememberedBaseMap(),'default');
assert.doesNotThrow(()=>denied.rememberBaseMap('satellite'));
assert(app.includes('state.baseMap=rememberedBaseMap()'));
assert(app.includes("rememberBaseMap('default')"),'Manual fallback/style switches should update the remembered choice');
assert(app.includes('Remembered choice reloads USGS tiles next time'));
assert(html.includes('name="map-basemap" value="satellite"'));
assert(html.includes('name="map-basemap" value="topographic"'));
console.log('PASS v0.2.148 persistent basemap preference with restricted storage fallback');
