'use strict';
const assert=require('node:assert/strict');
const {profileOptions}=require('../openrf/static/cellular-map.js');
const tech='4G LTE 5/1 Mbps',env='Outdoor stationary (all)';
const ca={carrier:'att',vintage:'2026-11-10',technology:tech,environment:env,fcc_file:'compact-v2/fcc-06-shared.sqlite3'};
const nv={...ca,vintage:'2026-11-24',fcc_file:'compact-v2/fcc-32-shared.sqlite3'};
const manual={carrier:'att',vintage:'2026-11-10',technology:tech,environment:env};
const combined=JSON.stringify(['att','fcc:all',tech,env]);
const result=profileOptions([ca,nv,{...nv,carrier:'tmobile'}],'att',JSON.stringify(['att',nv.vintage,tech,env]));
assert.equal(result.options.length,1);assert.equal(result.selected,combined);assert.match(result.options[0].label,/2026-11-10 to 2026-11-24/);
assert.equal(profileOptions([ca,nv],'att',JSON.stringify(['att',ca.vintage,tech,env])).selected,combined);
assert.equal(profileOptions([ca,nv],'att',combined).selected,combined);
const manualKey=JSON.stringify(['att','manual:'+manual.vintage,tech,env]);
const mixed=profileOptions([ca,nv,manual],'att',manualKey);assert.equal(mixed.options.length,2);assert.equal(mixed.selected,manualKey);
assert.equal(profileOptions([ca,nv,manual],'att').selected,combined);
assert.equal(profileOptions([ca,nv,manual],'att',JSON.stringify(['att',ca.vintage,tech,env])).selected,combined);
assert.equal(profileOptions([manual],'att',JSON.stringify(['att',manual.vintage,tech,env])).selected,manualKey);
assert.equal(profileOptions([ca,nv],'verizon').options.length,0);
console.log('FCC multistate profile grouping, date migration and manual import compatibility passed');
