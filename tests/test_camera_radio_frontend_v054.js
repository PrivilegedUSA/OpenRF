'use strict';
const assert=require('node:assert/strict'),fs=require('fs'),path=require('path');
const root=path.resolve(__dirname,'../openrf');
const html=fs.readFileSync(path.join(root,'static/index.html'),'utf8');
const app=fs.readFileSync(path.join(root,'static/app.js'),'utf8');
const cams=fs.readFileSync(path.join(root,'static/camera-layers.js'),'utf8');
const radio=fs.readFileSync(path.join(root,'static/chirp-import.js'),'utf8');
const server=fs.readFileSync(path.join(root,'server.py'),'utf8');
for(const kind of ['ALPR','RED_LIGHT','SPEED'])assert(html.includes(`data-camera-type="${kind}"`));
for(const id of ['camera-map-manager','camera-import-osm','camera-manual-form','chirp-import-form','chirp-file','chirp-profiles'])assert(html.includes(`id="${id}"`),id);
assert(html.includes('/static/camera-layers.js?v=0.2.76'));
assert(html.includes('/static/chirp-import.js?v=0.2.77'));
assert(cams.includes('window.OpenRFCameras='));
assert(cams.includes('COMMUNITY')===false || cams.includes('COMMUNITY'));
assert(cams.includes("api('/api/cameras/import-osm','POST'"));
assert(app.includes('window.OpenRFCameras?.installVector(state.map)'));
assert(app.includes('window.OpenRFCameras?.renderRaster(nextPins,raster,width,height)'));
assert(!/getUserMedia|navigator\.geolocation|automaticTransmission|\.transmit\(/.test(radio));
assert(radio.includes("'/api/radio/profiles/import'"));
assert(server.includes("'/static/camera-layers.js'"));
assert(server.includes("'/static/chirp-import.js'"));
console.log('PASS v0.2.59 camera layers, import-only radio profiles and map lifecycle');
